// Compiles modules/script-engine/js/prelude.js into a Swift string constant.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../modules/script-engine/', import.meta.url));
const js = readFileSync(root + 'js/prelude.js', 'utf8');
if (js.includes('"""#')) throw new Error('prelude.js cannot contain """#');

const swift = `// Generated by scripts/gen-prelude.mjs from js/prelude.js. Do not edit.
enum Prelude {
  static let source = #"""
${js}
"""#
}
`;
writeFileSync(root + 'ios/Prelude.swift', swift);
console.log('Wrote ios/Prelude.swift');
