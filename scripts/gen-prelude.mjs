// Compiles modules/script-engine/js/prelude.js (with its includes) into a Swift string constant.
import { writeFileSync } from 'node:fs';
import { jsDir, preludeSource } from './prelude-source.mjs';

const js = preludeSource();
// Both would end or interpolate into the Swift raw string literal.
if (js.includes('"""#') || js.includes('\\#')) throw new Error('prelude.js cannot contain """# or \\#');

const swift = `// Generated by scripts/gen-prelude.mjs from js/prelude.js. Do not edit.
enum Prelude {
  static let source = #"""
${js}
"""#
}
`;
writeFileSync(jsDir + '../ios/Prelude.swift', swift);
console.log('Wrote ios/Prelude.swift');
