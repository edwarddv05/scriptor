// Compiles modules/script-engine/js/prelude.js (with its includes) into a Swift string constant,
// and the Python page (python-runtime.js + scriptor_py.py) into another.
import { writeFileSync } from 'node:fs';
import { jsDir, preludeSource } from './prelude-source.mjs';
import { pythonPage } from './python-page.mjs';

const js = preludeSource();
// Both would end or interpolate into the Swift raw string literal.
if (js.includes('"""#') || js.includes('\\#')) throw new Error('prelude.js cannot contain """# or \\#');

const swift = `// Generated by scripts/gen-prelude.mjs from js/prelude.js. Do not edit.
enum Prelude {
  static let source = #"""
${js}
"""#
}
`;
writeFileSync(jsDir + '../ios/Prelude.swift', swift);
console.log('Wrote ios/Prelude.swift');

const page = pythonPage();
if (page.includes('"""#') || page.includes('\\#')) throw new Error('The Python page cannot contain """# or \\#');
writeFileSync(
  jsDir + '../ios/PythonPage.swift',
  `// Generated by scripts/gen-prelude.mjs from js/python-runtime.js and js/scriptor_py.py. Do not edit.
enum PythonPage {
  static let html = #"""
${page}
"""#
}
`
);
console.log('Wrote ios/PythonPage.swift');
