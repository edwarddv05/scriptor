// Bundles editor/main.js (CodeMirror) into one offline HTML string for the WebView.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const result = await build({
  entryPoints: [root + 'editor/main.js'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'safari16',
  write: false,
});
const js = result.outputFiles[0].text;

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html,body,#editor{margin:0;height:100%;background:#fff}@media (prefers-color-scheme:dark){html,body,#editor{background:#282c34}}</style>
</head><body><div id="editor"></div><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;

writeFileSync(
  root + 'src/editor/editor-html.ts',
  `// Generated by scripts/build-editor.mjs. Do not edit.\nexport const EDITOR_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Wrote src/editor/editor-html.ts (${Math.round(html.length / 1024)} KB)`);
